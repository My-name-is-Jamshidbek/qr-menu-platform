/**
 * Generates `src/i18n/catalog.generated.ts` from the JSON files in `messages/`.
 *
 * The catalog has to be a *static* import map: `src/i18n/request.ts` and the
 * locale proxy run in the edge runtime, where `fs` and dynamic `import()` of a
 * computed path are not available. Scanning the directory at build time and
 * emitting explicit imports keeps the runtime static while still letting other
 * contributors add `messages/<locale>/<namespace>.json` without editing code.
 *
 * Run via `npm run gen:messages` (also wired to `predev` / `prebuild`).
 */
import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const messagesDir = join(projectRoot, 'messages');
const outputFile = join(projectRoot, 'src', 'i18n', 'catalog.generated.ts');

/** Must stay in sync with `locales` in `src/i18n/routing.ts`. */
const LOCALES = ['uz', 'ru', 'en'];
const DEFAULT_LOCALE = 'uz';

/** `common` -> `Common`, `table-qr` -> `TableQr`. */
function toPascalCase(value) {
  return value
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

function readNamespaces(locale) {
  let entries;
  try {
    entries = readdirSync(join(messagesDir, locale), {withFileTypes: true});
  } catch {
    throw new Error(`Missing message directory: messages/${locale}`);
  }

  const namespaces = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.json'))
    .map((entry) => entry.name.slice(0, -'.json'.length))
    .sort();

  for (const namespace of namespaces) {
    // Fail loudly on malformed JSON now rather than at request time.
    JSON.parse(readFileSync(join(messagesDir, locale, `${namespace}.json`), 'utf8'));
  }

  return namespaces;
}

function generate() {
  const byLocale = new Map(LOCALES.map((locale) => [locale, readNamespaces(locale)]));

  const defaultNamespaces = byLocale.get(DEFAULT_LOCALE) ?? [];
  if (defaultNamespaces.length === 0) {
    throw new Error(`No message files found in messages/${DEFAULT_LOCALE}`);
  }

  const imports = [];
  const localeEntries = [];

  for (const locale of LOCALES) {
    const namespaces = byLocale.get(locale) ?? [];
    const missing = defaultNamespaces.filter((namespace) => !namespaces.includes(namespace));
    if (missing.length > 0) {
      throw new Error(
        `messages/${locale} is missing namespace file(s): ${missing.join(', ')}. ` +
          `Every locale must define the same namespaces as ${DEFAULT_LOCALE}.`
      );
    }

    const properties = namespaces.map((namespace) => {
      const identifier = `${locale}${toPascalCase(namespace)}`;
      imports.push(`import ${identifier} from '../../messages/${locale}/${namespace}.json';`);
      return `    ${JSON.stringify(namespace)}: ${identifier}`;
    });

    localeEntries.push(`  ${locale}: {\n${properties.join(',\n')}\n  }`);
  }

  const source = `// AUTO-GENERATED by scripts/generate-message-catalog.mjs — do not edit by hand.
// Run \`npm run gen:messages\` after adding or removing a file in messages/.
${imports.sort().join('\n')}

/**
 * Every namespace of every locale, keyed by \`messages/<locale>/<namespace>.json\`.
 * Static imports only, so this module is safe in the edge runtime.
 */
export const messageCatalog = {
${localeEntries.join(',\n')}
} as const;

export type MessageCatalog = typeof messageCatalog;
`;

  writeFileSync(outputFile, source, 'utf8');
  const namespaceCount = defaultNamespaces.length;
  process.stdout.write(
    `Generated src/i18n/catalog.generated.ts (${LOCALES.length} locales x ${namespaceCount} namespaces)\n`
  );
}

generate();
